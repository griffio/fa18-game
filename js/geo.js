// islands in the bay that are big enough for the terrain grid
function ellipse(lat, lon, rxM, rzM, rotDeg, n = 14, wobble = 0.12, seed = 1) {
  const [cx, cz] = ll(lat, lon);
  const r = rotDeg * Math.PI / 180;
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    const k = 1 + wobble * Math.sin(a * 3 + seed) * Math.cos(a * 2 + seed * 2);
    const x = Math.cos(a) * rxM * k, z = Math.sin(a) * rzM * k;
    pts.push([cx + x * Math.cos(r) - z * Math.sin(r), cz + x * Math.sin(r) + z * Math.cos(r)]);
  }
  return pts;
}
