// San Francisco Bay Area geography - the setting of F/A-18 Interceptor.
// Coordinates are given as real latitude/longitude and converted to a local
// tangent plane with the origin at the middle of the Golden Gate Bridge.
//   x = metres east, z = metres south.
const LAT0 = 37.8199, LON0 = -122.4783;
const M_PER_DEG_LAT = 111030;
const M_PER_DEG_LON = 111320 * Math.cos(LAT0 * Math.PI / 180);

export function ll(lat, lon) {
  return [(lon - LON0) * M_PER_DEG_LON, (LAT0 - lat) * M_PER_DEG_LAT];
}
export function llXZ(arr) { return arr.map(([la, lo]) => ll(la, lo)); }

