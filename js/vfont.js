// Emit strokes for `str`. Calls seg(x1,y1,x2,y2) in output units.
// size = cap height; returns width.
export function textSegments(str, x, y, size, align, seg, spacing = 1.5) {
  const s = size / 6;
  const adv = (4 + spacing) * s;
  const w = str.length * adv - spacing * s;
  let x0 = x;
  if (align === 'center') x0 = x - w / 2;
  else if (align === 'right') x0 = x - w;
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    const g = G[ch] || G[ch.toUpperCase()];
    if (g) {
      for (const pl of g) {
        for (let k = 0; k < pl.length - 2; k += 2) {
          seg(x0 + pl[k] * s, y + pl[k + 1] * s, x0 + pl[k + 2] * s, y + pl[k + 3] * s);
        }
      }
    }
    x0 += adv;
  }
  return w;
}
export function textWidth(str, size, spacing = 1.5) {
  const s = size / 6;
  return str.length * (4 + spacing) * s - spacing * s;
}
